#!/usr/bin/env bash
# Regenerate .claude/hooks/README.md from the tree. The hand-written one drifted far
# enough that most scripts went unnamed and a stranger could not reconstruct the
# active set. A generated table cannot drift; CI runs this with --check.
#
# Each row is: script, the lifecycle event it is wired to, and its one-line purpose,
# taken from the first comment line after the shebang. Wiring comes from
# settings.json, which is not tracked, so an absent one yields dashes.
#
#   gen-hooks-readme.sh           rewrite the file
#   gen-hooks-readme.sh --check   exit 1 if it would change
set -uo pipefail
root="$(git rev-parse --show-toplevel)"; cd "$root"
OUT=".claude/hooks/README.md"
SETTINGS="${KC_SETTINGS:-$HOME/.claude/settings.json}"

event_of() {  # $1 = basename; prints the events it is wired to, or a dash
  [ -f "$SETTINGS" ] || { printf -- '-'; return; }
  python3 - "$SETTINGS" "$1" <<'PY'
import json, sys
try: d = json.load(open(sys.argv[1]))
except Exception: print("-"); raise SystemExit
ev = [e for e, arr in d.get("hooks", {}).items()
      for m in arr for h in m.get("hooks", []) if sys.argv[2] in h.get("command", "")]
print(", ".join(dict.fromkeys(ev)) or "-")
PY
}

purpose_of() {  # first comment line after the shebang, trimmed
  sed -n '2,6p' "$1" | grep -m1 '^# ' | sed 's/^# *//' | cut -c1-96
}

gen() {
  cat <<'HDR'
# Hooks

Generated by `scripts/gen-hooks-readme.sh`; do not edit by hand. CI runs it with
`--check`, so an added hook that is not listed here fails the build.

**Event** is where the script is wired in `settings.json`. A dash means it is not
wired as a hook: it is a library other hooks source, or a command you run yourself.

Every value that would identify a machine lives in `local.env`, which is gitignored.
`local.env.example` lists the keys. Unset keys make the affected check inert rather
than making it misfire, so a fresh clone runs without configuration.

HDR
  printf '| script | event | purpose |\n|-|-|-|\n'
  for f in $(ls .claude/hooks/*.sh | sort); do
    b=$(basename "$f")
    printf '| `%s` | %s | %s |\n' "$b" "$(event_of "$b")" "$(purpose_of "$f")"
  done
  printf '\nSuperseded versions are kept under `archive/` so a later pass does not silently\n'
  printf 're-add something that was deliberately removed.\n'
}

if [ "${1:-}" = "--check" ]; then
  if ! diff -q <(gen) "$OUT" >/dev/null 2>&1; then
    echo "$OUT is stale; run scripts/gen-hooks-readme.sh" >&2
    diff <(gen) "$OUT" | head -20 >&2
    exit 1
  fi
  echo "hooks README current"; exit 0
fi
gen > "$OUT"
echo "wrote $OUT"
